document.addEventListener('DOMContentLoaded', () => {

    const ui = {
        totalAnomalies: document.getElementById('total-anomalies'),
        maxScore: document.getElementById('max-score'),
        avgLead: document.getElementById('avg-lead'),
        lastUpdated: document.getElementById('last-updated'),
        list: document.getElementById('anomalies-list'),
        guideModal: document.getElementById('guide-modal'),
        guideTrigger: document.getElementById('guide-trigger'),
        guideClose: document.getElementById('close-guide'),
        searchInput: document.getElementById('search-input'),
        regionFilter: document.getElementById('region-filter')
    };

    let allAnomalies = [];

    // Modal logic
    const showGuide = () => ui.guideModal.classList.remove('hidden');
    const hideGuide = () => ui.guideModal.classList.add('hidden');

    ui.guideTrigger.addEventListener('click', showGuide);
    ui.guideClose.addEventListener('click', hideGuide);

    // Auto-show guide for first-time visitors
    if (!localStorage.getItem('ob1_visited')) {
        showGuide();
        localStorage.setItem('ob1_visited', 'true');
    }

    // Load data from JSON (generated by Python script)
    async function loadData() {
        try {
            const res = await fetch(`data/anomalies.json?t=${new Date().getTime()}`);
            if (!res.ok) throw new Error('Data not found');
            const data = await res.json();
            renderDashboard(data);
        } catch (error) {
            console.error('Failed to load data:', error);
            ui.list.innerHTML = `
                <div class="loader-container">
                    <p style="color: var(--accent-red)">⚠️ RADAR OFFLINE</p>
                    <p style="font-size: 0.75rem; margin-top: 5px;">Awaiting Ouroboros Sync...</p>
                </div>
            `;
        }
    }

    function renderDashboard(anomalies) {
        allAnomalies = anomalies;

        // Populate region filter (only on first load or if regions change)
        const regions = [...new Set(anomalies.map(a => a.region).filter(Boolean))].sort();
        const currentRegion = ui.regionFilter.value;
        ui.regionFilter.innerHTML = '<option value="">All Regions</option>';
        regions.forEach(r => {
            const opt = document.createElement('option');
            opt.value = r;
            opt.textContent = r;
            if (r === currentRegion) opt.selected = true;
            ui.regionFilter.appendChild(opt);
        });

        applyFilters();
    }

    function applyFilters() {
        const query = (ui.searchInput.value || '').toLowerCase();
        const region = ui.regionFilter.value;

        let filtered = allAnomalies;
        if (query) {
            filtered = filtered.filter(a => {
                const haystack = [a.player_name, a.club, a.region, a.position, a.league]
                    .filter(Boolean).join(' ').toLowerCase();
                return haystack.includes(query);
            });
        }
        if (region) {
            filtered = filtered.filter(a => a.region === region);
        }

        ui.totalAnomalies.textContent = filtered.length;

        if (filtered.length > 0) {
            const max = Math.max(...filtered.map(a => a.score));
            ui.maxScore.innerHTML = `${Math.round(max)}<span class="muted">/100</span>`;

            const confirmed = filtered.filter(a => a.lead_time_days && a.lead_time_days > 0);
            if (confirmed.length > 0) {
                const avgLead = Math.round(confirmed.reduce((s, a) => s + a.lead_time_days, 0) / confirmed.length);
                ui.avgLead.innerHTML = `+${avgLead}<span class="muted">d</span>`;
            } else {
                ui.avgLead.innerHTML = `<span class="muted" style="font-size:0.9rem">tracking</span>`;
            }

            const latest = filtered[0].detection_date;
            if (latest) {
                const dt = new Date(latest);
                ui.lastUpdated.textContent = dt.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
            }

            ui.list.innerHTML = '';
            filtered.sort((a, b) => b.score - a.score).forEach((anomaly, index) => {
                const el = createAnomalyCard(anomaly, index * 0.05);
                ui.list.appendChild(el);
            });
        } else {
            ui.list.innerHTML = `<div class="loader-container"><p>No matches found.</p></div>`;
        }
    }

    function createAnomalyCard(anomaly, delay) {
        const div = document.createElement('div');
        div.className = `anomaly-item`;
        div.style.animation = `slideUp 0.5s ease backwards ${delay}s`;

        const score = Math.round(anomaly.score || 0);
        const radius = 26;
        const circumference = 2 * Math.PI * radius;
        const offset = circumference - (score / 100) * circumference;

        const dateObj = new Date(anomaly.detection_date);
        const dateStr = `${dateObj.getDate()}/${dateObj.getMonth() + 1} - ${dateObj.getHours()}:${String(dateObj.getMinutes()).padStart(2, '0')}`;

        const isGhost = !!anomaly.is_ghost;

        // Build player subtitle (age | position | club)
        const subParts = [];
        if (anomaly.age) subParts.push(`${anomaly.age}y`);
        if (anomaly.position) {
            // Clean position: take first word/abbreviation only
            const pos = anomaly.position.split(/[\s(,/]/)[0];
            subParts.push(pos);
        }
        if (anomaly.club) {
            // Clean club: take first part before parentheses, max 30 chars
            let clubStr = anomaly.club.split(/[(\[]/)[0].trim();
            if (clubStr.length > 30) clubStr = clubStr.substring(0, 28) + '…';
            subParts.push(clubStr);
        }
        if (anomaly.league) {
            let leagueStr = anomaly.league.split(/[/]/)[0].trim();
            if (leagueStr.length > 30) leagueStr = leagueStr.substring(0, 28) + '…';
            subParts.push(leagueStr);
        }
        const subtitle = subParts.length > 0 ? subParts.join(' · ') : '';

        // Extract clean stat numbers from raw stats text
        let statsHtml = '';
        if (anomaly.stats_summary) {
            const s = anomaly.stats_summary;
            const parts = [];
            const mp = s.match(/(?:MP|Appearances)[.\s:]*(\d+)/i);
            if (mp) parts.push(`MP: ${mp[1]}`);
            const gls = s.match(/(?:Gls|Goals)[.\s:]*(\d+)/i);
            if (gls) parts.push(`G: ${gls[1]}`);
            const ast = s.match(/(?:Ast|Assists)[.\s:]*(\d+)/i);
            if (ast) parts.push(`A: ${ast[1]}`);
            const mins = s.match(/(?:Min|Minutes)[.\s:]*(\d[\d,']*)/i);
            if (mins) parts.push(`${mins[1]}'`);
            if (parts.length > 0) {
                statsHtml = `<div class="item-stats"><code>${parts.join(' · ')}</code></div>`;
            }
        }

        // Sparkline from score_history
        let sparklineHtml = '';
        try {
            const history = typeof anomaly.score_history === 'string'
                ? JSON.parse(anomaly.score_history) : anomaly.score_history;
            if (history && history.length >= 2) {
                const scores = history.map(h => h.score);
                const min = Math.min(...scores, 0);
                const max = Math.max(...scores, 100);
                const w = 120, h = 28, pad = 2;
                const points = scores.map((s, i) => {
                    const x = pad + (i / (scores.length - 1)) * (w - pad * 2);
                    const y = pad + (1 - (s - min) / (max - min || 1)) * (h - pad * 2);
                    return `${x},${y}`;
                }).join(' ');
                const last = scores[scores.length - 1];
                const first = scores[0];
                const color = last >= first ? 'var(--accent-green, #00ff88)' : 'var(--accent-red, #ff4444)';
                sparklineHtml = `
                    <div class="item-sparkline">
                        <svg width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
                            <polyline points="${points}" fill="none" stroke="${color}" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" opacity="0.8"/>
                        </svg>
                        <span class="sparkline-label">${scores.length} detections</span>
                    </div>`;
            }
        } catch(e) {}

        // Clean raw_content: strip the "Stats:" tail we appended in pipeline
        let reason = anomaly.raw_content || '';
        const statsIdx = reason.indexOf('\n\nStats:');
        if (statsIdx > 0) reason = reason.substring(0, statsIdx);

        div.innerHTML = `
            <div class="item-header">
                <div class="player-info">
                    <h4>${anomaly.player_name}</h4>
                    ${subtitle ? `<span class="item-subtitle">${subtitle}</span>` : ''}
                    <span class="item-region">
                        <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"></circle><path d="M2 12h20"></path><path d="M12 2a15.3 15.3 0 0 1 4 10 15.3 15.3 0 0 1-4 10 15.3 15.3 0 0 1-4-10 15.3 15.3 0 0 1 4-10z"></path></svg>
                        ${anomaly.region || 'Unknown Sector'}
                    </span>
                    <div class="item-badges">
                        ${isGhost ? '<span class="ghost-badge">GHOST PROTOCOL</span>' : ''}
                        ${(anomaly.detection_count || 1) > 1 ? `<span class="track-badge">TRACKED x${anomaly.detection_count}</span>` : ''}
                        ${anomaly.lead_time_days > 0 ? `<span class="lead-badge">LEAD +${anomaly.lead_time_days}d</span>` : ''}
                    </div>
                </div>
                <div class="player-score-container">
                    <svg class="score-ring" width="60" height="60">
                        <circle class="ring-bg" cx="30" cy="30" r="${radius}" />
                        <circle class="ring-fill" cx="30" cy="30" r="${radius}"
                                style="stroke-dasharray: ${circumference}; stroke-dashoffset: ${offset};" />
                    </svg>
                    <div class="score-value">${score}</div>
                </div>
            </div>

            <div class="item-metrics">
                <div class="metric">
                    <span>Lead Time</span>
                    <strong>${anomaly.lead_time_days > 0 ? `+${anomaly.lead_time_days}d` : 'tracking'}</strong>
                </div>
                <div class="metric">
                    <span>First Detected</span>
                    <strong>${dateStr}</strong>
                </div>
            </div>

            ${sparklineHtml}

            <div class="item-context">
                ${reason || 'Analyzing information asymmetry...'}
            </div>

            ${statsHtml}

            ${anomaly.sources && anomaly.sources.length > 0 ? `
                <div class="item-sources">
                    <div class="sources-toggle">
                        <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4"></path><polyline points="7 10 12 15 17 10"></polyline><line x1="12" y1="15" x2="12" y2="3"></line></svg>
                        SOURCE
                    </div>
                    <div class="sources-list">
                        ${anomaly.sources.map(s => { try { return `<a href="${s}" target="_blank" class="source-link">${new URL(s).hostname.replace('www.', '')}</a>`; } catch(e) { return ''; } }).join('')}
                    </div>
                </div>
            ` : ''}
        `;

        return div;
    }

    // Filter events
    ui.searchInput.addEventListener('input', applyFilters);
    ui.regionFilter.addEventListener('change', applyFilters);

    // Init
    loadData();
    setInterval(loadData, 300000);
});
